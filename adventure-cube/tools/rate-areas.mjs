// rate-areas.mjs - rate the 3 main areas with the AI rater and store the results (INTEGRATE).
//   node tools/rate-areas.mjs [area1 area2 area3] [--budget 120000]
// Writes src/ui/ratings.js (difficulty + stats shown in the menu) and tools/routes/<id>.json (the AI's winning
// inputs, replayed by tools/playtest.cjs). Merges with ratings already in the file.
import fs from "fs";
import path from "path";
import { pathToFileURL, fileURLToPath } from "url";
import { rateLevel } from "../src/ai/rater.js";
import { createSim } from "../src/sim/index.js";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const args = process.argv.slice(2);
const bi = args.indexOf("--budget");
const budgetMs = bi >= 0 ? +args[bi + 1] : 120000;
const ids = args.filter((a, i) => /^area\d$/.test(a) && args[i - 1] !== "--budget");
const OUT = path.join(ROOT, "src", "ui", "ratings.js");
const ROUTES = path.join(HERE, "routes");
fs.mkdirSync(ROUTES, { recursive: true });

let cur = {};
try { cur = (await import(pathToFileURL(OUT).href + "?t=" + Date.now())).RATINGS || {}; } catch (e) { cur = {}; }
for (const id of ids.length ? ids : ["area1", "area2", "area3"]) {
  const lv = (await import(pathToFileURL(path.join(ROOT, "src", "levels", id + ".js")).href)).default;
  const t0 = Date.now();
  const r = rateLevel(lv, { budgetMs });
  let replay = null;
  if (r.beatable && r.inputs) {
    const sim = createSim(lv, { events: false }); sim.run(r.inputs);
    replay = { won: sim.state.won, deaths: sim.state.deaths, frame: sim.state.winFrame };
    fs.writeFileSync(path.join(ROUTES, id + ".json"), JSON.stringify({ id, frames: r.inputs.length, inputs: Array.from(r.inputs) }));
  }
  const s = r.stats || {};
  cur[id] = { difficulty: r.difficulty, beatable: r.beatable, score: s.score ?? null, seconds: s.seconds ?? null,
    segments: (s.segments || []).map((x) => x.difficulty), rated: new Date().toISOString().slice(0, 10) };
  console.log(id, JSON.stringify(cur[id]), "replay", JSON.stringify(replay), ((Date.now() - t0) / 1000).toFixed(1) + "s");
}
fs.writeFileSync(OUT, "// ratings.js - AI rater results for the main areas (generated by tools/rate-areas.mjs; INTEGRATE).\n" +
  "// difficulty 1..10 (1 easy, 5 hard, 10 impossible). The menu shows these as badges.\n" +
  "export const RATINGS = " + JSON.stringify(cur, null, 1) + ";\n");
console.log("wrote", OUT);

// the title screen's attract mode replays the AI's area1 route: store it run-length encoded ("<bits><count base36>,")
const r1 = path.join(ROUTES, "area1.json");
if (fs.existsSync(r1)) {
  const inp = JSON.parse(fs.readFileSync(r1, "utf8")).inputs;
  const runs = [];
  for (let i = 0; i < inp.length;) { let j = i; while (j < inp.length && inp[j] === inp[i]) j++; runs.push(inp[i] + (j - i).toString(36)); i = j; }
  fs.writeFileSync(path.join(ROOT, "src", "ui", "attract.js"), "// attract.js - the AI's winning area1 route, run-length encoded (generated by tools/rate-areas.mjs).\n" +
    "// Each item: first char = input bits (0-7), rest = run length in base 36.\n" +
    `export const ATTRACT_ROUTE = "${runs.join(",")}";\n` +
    "export function decodeRoute(s) { const out = []; for (const r of s.split(\",\")) { const b = +r[0], n = parseInt(r.slice(1), 36); for (let i = 0; i < n; i++) out.push(b); } return Uint8Array.from(out); }\n");
  console.log("wrote attract.js", runs.length, "runs");
}
